#!/usr/bin/env node
// Bundles unit files into data/content.js and writes sw.js with a precache list + content hash.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const udir = path.join(root, 'data/units');
const order = f => { const m = /^g(1[12])u(\d+)\.js$/.exec(f); return m ? (+m[1]) * 100 + (+m[2]) : 1e9; };
const only = process.argv.slice(2);
const units = fs.readdirSync(udir).filter(f => order(f) < 1e9 && (!only.length || only.includes(f.replace('.js', '')))).sort((a, b) => order(a) - order(b));
let bundle = '/* generated by tools/build.js — do not edit */\n';
for (const f of units) bundle += `\n/* ${f} */\n` + fs.readFileSync(path.join(udir, f), 'utf8') + '\n';
const xdir = path.join(root, 'data/extras');
if (fs.existsSync(xdir)) for (const f of fs.readdirSync(xdir).filter(f => f.endsWith('.js')).sort()) bundle += `\n/* extras/${f} */\n` + fs.readFileSync(path.join(xdir, f), 'utf8') + '\n';
fs.writeFileSync(path.join(root, 'data/content.js'), bundle);
const list = d => fs.readdirSync(path.join(root, d)).filter(f => !f.startsWith('.')).sort().map(f => d + '/' + f);
const files = ['./', 'index.html', 'manifest.webmanifest', ...list('css').filter(f => f.endsWith('.css')), ...list('js').filter(f => f.endsWith('.js')), 'data/content.js',
  ...fs.readdirSync(path.join(root, 'fonts')).filter(f => f.endsWith('.woff2')).map(f => 'fonts/' + f),
  ...fs.readdirSync(path.join(root, 'icons')).filter(f => f.endsWith('.png')).map(f => 'icons/' + f)];
const h = crypto.createHash('sha256');
files.filter(f => f !== './').forEach(f => h.update(fs.readFileSync(path.join(root, f))));
const ver = h.digest('hex').slice(0, 10);
const sw = `/* generated by tools/build.js */
const CACHE = 'tafawuq-${ver}';
const FILES = ${JSON.stringify(files, null, 0)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('tafawuq-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => req.mode === 'navigate' ? caches.match('index.html') : Response.error())));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`bundled ${units.length} units (${(bundle.length / 1024).toFixed(0)} KB) · cache ${ver} · ${files.length} files`);
